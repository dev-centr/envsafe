#!/usr/bin/env bash
# Write packaging/aur/PKGBUILD, packaging/aur/.SRCINFO and packaging/nix/sources.json
# from a release's SHA256SUMS.txt. Usage: render.sh <version> <SHA256SUMS.txt>
set -euo pipefail
v="$1"; sums="$2"
here="$(cd "$(dirname "$0")/.." && pwd)"
sha() { local s; s="$(awk -v f="$1" '$2==f {print $1}' "$sums")"; [ -n "$s" ] || { echo "missing checksum for $1" >&2; exit 1; }; echo "$s"; }
base="https://github.com/dev-centr/envsafe/releases/download/v$v"
x64="envsafe-$v-linux-x64.tar.gz"; a64="envsafe-$v-linux-arm64.tar.gz"
mac="envsafe-$v-macos-universal.tar.gz"
grep -q " $mac\$" "$sums" || mac="envsafe-$v-macos-arm64.tar.gz"
sx="$(sha "$x64")"; sa="$(sha "$a64")"; sm="$(sha "$mac")"

cat > "$here/aur/PKGBUILD" <<PKG
# Maintainer: Ryan Johnson <ryan.johnson.code@gmail.com>
# Generated by packaging/aur/render.sh; edit that script, not this file.
pkgname=envsafe-bin
pkgver=$v
pkgrel=1
pkgdesc="Secret-safe .env editing for people and AI agents"
arch=('x86_64' 'aarch64')
url="https://github.com/dev-centr/envsafe"
license=('MIT')
depends=('glibc')
provides=('envsafe')
conflicts=('envsafe')
source_x86_64=("$base/$x64")
source_aarch64=("$base/$a64")
sha256sums_x86_64=('$sx')
sha256sums_aarch64=('$sa')

package() {
  install -Dm755 envsafe "\$pkgdir/usr/bin/envsafe"
  install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  install -Dm644 README.md "\$pkgdir/usr/share/doc/\$pkgname/README.md"
}
PKG

cat > "$here/aur/.SRCINFO" <<SRC
pkgbase = envsafe-bin
	pkgdesc = Secret-safe .env editing for people and AI agents
	pkgver = $v
	pkgrel = 1
	url = https://github.com/dev-centr/envsafe
	arch = x86_64
	arch = aarch64
	license = MIT
	depends = glibc
	provides = envsafe
	conflicts = envsafe
	source_x86_64 = $base/$x64
	sha256sums_x86_64 = $sx
	source_aarch64 = $base/$a64
	sha256sums_aarch64 = $sa

pkgname = envsafe-bin
SRC

cat > "$here/nix/sources.json" <<JSON
{
  "version": "$v",
  "x86_64-linux": { "url": "$base/$x64", "sha256": "$sx" },
  "aarch64-linux": { "url": "$base/$a64", "sha256": "$sa" },
  "aarch64-darwin": { "url": "$base/$mac", "sha256": "$sm" },
  "x86_64-darwin": { "url": "$base/$mac", "sha256": "$sm" }
}
JSON
